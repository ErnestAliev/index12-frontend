import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';

export async function verifyBusinessUi({ apiUrl, entitiesApiUrl, actor, workspaceId, company, profile }) {
  const taskDate = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Almaty' }).format(new Date());
  const output = fileURLToPath(new URL('../../output/playwright/', import.meta.url));
  const server = await createServer({ root: fileURLToPath(new URL('../../', import.meta.url)), server: { host: '127.0.0.1', port: 5192, strictPort: true } });
  let browser;
  try {
    await server.listen();
    browser = await chromium.launch({ executablePath: process.env.SCROLL_TEST_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    let syncRequests = 0;
    await page.context().route('**/api/**', async route => {
      const request = route.request(), path = new URL(request.url()).pathname;
      if (path.startsWith('/api/business')) {
        if (path.endsWith('/sync-onec') && request.method() === 'POST') syncRequests++;
        const response = await route.fetch({ url: apiUrl + path.slice(4) + new URL(request.url()).search, headers: { ...request.headers(), 'x-test-actor': actor, 'x-test-workspace': workspaceId, origin: 'http://127.0.0.1:5192' } });
        return route.fulfill({ response });
      }
      if (/^\/api\/(companies|contractors|accounts)(\/|$)/.test(path)) {
        const response = await route.fetch({ url: entitiesApiUrl + path.slice(4) }); return route.fulfill({ response });
      }
      let data = [];
      if (path.endsWith('/auth/me')) data = { _id: actor, id: actor, name: 'Проверка', role: 'admin', workspaceRole: 'admin', currentWorkspaceId: workspaceId };
      if (path.endsWith('/workspaces')) data = [{ _id: workspaceId, name: 'Проверка', userId: actor, isDefault: true }];
      if (path.endsWith('/snapshot')) data = { timestamp: new Date().toISOString(), accountBalances: {}, companyBalances: {}, individualBalances: {}, contractorBalances: {} };
      if (path.endsWith('/appearance-themes')) data = { themes: [] };
      if (path.endsWith('/appearance-templates')) data = { templates: [] };
      if (path.endsWith('/codex/status')) data = { connected: false, configured: false };
      return route.fulfill({ json: data });
    });
    await page.goto('http://127.0.0.1:5192/');
    await page.getByRole('button', { name: 'Открыть календарь задач', exact: true }).click();
    const calendar = page.getByRole('dialog', { name: 'Календарь задач', exact: true });
    await calendar.getByRole('button', { name: '+ Задача', exact: true }).click();
    await calendar.getByRole('textbox', { name: 'Название задачи', exact: true }).fill('Сверить налоговые уведомления');
    await calendar.getByRole('combobox', { name: 'Компания задачи', exact: true }).selectOption(company._id);
    await calendar.getByLabel('Дата задачи', { exact: true }).fill(taskDate);
    await calendar.getByRole('button', { name: 'Сохранить задачу', exact: true }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Открыть календарь задач', exact: true }).click();
    const day = calendar.getByRole('button', { name: new RegExp(`^${taskDate},`) });
    await day.click();
    await calendar.getByRole('button', { name: 'Сверить налоговые уведомления', exact: true }).waitFor();
    await calendar.getByRole('combobox', { name: 'Фильтр по компании', exact: true }).selectOption(company._id);
    await calendar.getByRole('checkbox', { name: 'Выполнить: Сверить налоговые уведомления', exact: true }).check();
    await calendar.getByRole('button', { name: 'Сверить налоговые уведомления', exact: true }).waitFor({ state: 'hidden' });
    await calendar.getByRole('checkbox', { name: 'Выполненные', exact: true }).check();
    await calendar.getByRole('button', { name: 'Сверить налоговые уведомления', exact: true }).waitFor();
    await mkdir(output, { recursive: true });
    await page.screenshot({ path: `${output}/business-calendar-desktop.png` });
    await calendar.getByRole('button', { name: 'Закрыть календарь', exact: true }).click();
    await page.locator('.contractor-editor-btn').click();
    await page.getByRole('button', { name: '+ Создать контрагента', exact: true }).click();
    const create = page.locator('.create-modal');
    await create.locator('.name-input').fill('Поставщик без номера');
    await create.getByRole('button', { name: 'Создать', exact: true }).click();
    await create.waitFor({ state: 'hidden' });
    await page.locator('.contractor-bin-cell button').first().click();
    const legal = page.getByRole('dialog', { name: 'Карточка контрагента', exact: true });
    await legal.getByRole('textbox', { name: 'БИН/ИИН', exact: true }).waitFor();
    assert.equal(await legal.getByRole('textbox', { name: 'БИН/ИИН', exact: true }).inputValue(), '');
    await legal.getByRole('button', { name: 'Синхронизировать с 1С', exact: true }).click();
    await legal.getByRole('combobox', { name: 'Запись из справочника 1С', exact: true }).selectOption('22222222-2222-4222-8222-222222222222');
    await legal.getByRole('button', { name: 'Связать и загрузить', exact: true }).click();
    await legal.getByText('Реквизиты загружены из 1С', { exact: true }).waitFor();
    assert.equal(await legal.getByRole('textbox', { name: 'БИН/ИИН', exact: true }).inputValue(), profile.identificationNumber);
    assert.equal(await legal.getByRole('textbox', { name: 'Название в INDEX12', exact: true }).inputValue(), 'Поставщик без номера');
    await legal.getByRole('button', { name: 'Закрыть карточку контрагента', exact: true }).click();
    await page.locator('.contractor-popup .modal-close-btn').click();
    await page.locator('.edit-btn').click();
    assert.equal(await page.getByRole('tab', { name: 'Компании и КГД', exact: true }).count(), 0);
    const ownerInput = page.getByRole('textbox', { name: 'Название владельца счета', exact: true }).first();
    const inputBox = await ownerInput.boundingBox();
    await ownerInput.click({ position: { x: inputBox.width - 34, y: inputBox.height / 2 } });
    await ownerInput.fill('ТОО Тест · сохранено');
    await page.locator('.editor-modal').getByRole('button', { name: 'Сохранить', exact: true }).click();
    await page.getByText('Изменения сохранены', { exact: true }).waitFor();
    const editorDraft = page.locator('.editor-modal .account-input-wrap input').first();
    await editorDraft.fill('Черновик названия счёта');
    const originalUrl = page.url(), pageCount = page.context().pages().length;
    await page.getByRole('button', { name: 'ТОО Тест · сохранено', exact: true }).first().click();
    const companyCard = page.getByRole('dialog', { name: 'Карточка компании', exact: true });
    await companyCard.getByRole('heading', { name: 'ТОО Тест · сохранено', exact: true }).waitFor();
    assert.equal(page.url(), originalUrl); assert.equal(page.context().pages().length, pageCount);
    assert.ok(await page.locator('.editor-modal').isVisible());
    assert.equal(await companyCard.getByRole('textbox', { name: 'Пароль ЭЦП', exact: true }).count(), 0);
    assert.ok((await companyCard.boundingBox()).width >= 1360, 'company card uses the available viewport');
    const beforeSync = syncRequests;
    await companyCard.getByRole('button', { name: 'Синхронизировать с 1С', exact: true }).click();
    const selection = companyCard.getByRole('combobox', { name: 'Запись из справочника 1С', exact: true });
    await selection.locator('option').filter({ hasText: 'ТОО Тест из 1С' }).waitFor({ state: 'attached' });
    assert.equal(await selection.inputValue(), '', 'even a sole organization requires explicit selection');
    assert.equal(syncRequests, beforeSync, 'opening candidates must not populate this company');
    await selection.selectOption('11111111-1111-4111-8111-111111111111');
    await companyCard.getByRole('button', { name: 'Связать и загрузить', exact: true }).click();
    await companyCard.getByText('Реквизиты загружены из 1С', { exact: true }).waitFor();
    assert.equal(await companyCard.getByRole('textbox', { name: 'БИН/ИИН', exact: true }).inputValue(), profile.identificationNumber);
    await companyCard.getByRole('textbox', { name: 'Руководитель', exact: true }).fill('Руководитель после правки');
    await companyCard.getByRole('button', { name: '+ Ссылка', exact: true }).click();
    const linkNumber = await companyCard.getByRole('textbox', { name: /^Внешняя ссылка / }).count();
    await companyCard.getByRole('textbox', { name: `Название ссылки ${linkNumber}`, exact: true }).fill('Отчёты компании');
    await companyCard.getByRole('textbox', { name: `Внешняя ссылка ${linkNumber}`, exact: true }).fill('https://drive.google.com/drive/folders/reports-test');
    await companyCard.getByRole('combobox', { name: `Назначение ссылки ${linkNumber}`, exact: true }).selectOption('reports');
    await companyCard.getByRole('button', { name: 'Сохранить', exact: true }).click();
    await companyCard.getByText('Реквизиты сохранены', { exact: true }).waitFor();
    const downloaded = page.waitForEvent('download');
    await companyCard.getByRole('button', { name: 'Скачать .txt', exact: true }).click();
    const download = await downloaded; assert.ok(download.suggestedFilename().endsWith('.txt'));
    await page.screenshot({ path: `${output}/business-company-desktop.png` });
    await companyCard.getByRole('button', { name: 'Закрыть карточку компании', exact: true }).click();
    await companyCard.waitFor({ state: 'hidden' });
    assert.equal(await editorDraft.inputValue(), 'Черновик названия счёта');
    await page.getByRole('button', { name: 'ТОО Тест · сохранено', exact: true }).first().click();
    await companyCard.getByRole('textbox', { name: 'Руководитель', exact: true }).waitFor();
    assert.equal(await companyCard.getByRole('textbox', { name: 'Руководитель', exact: true }).inputValue(), 'Руководитель после правки');
    assert.equal(await companyCard.getByRole('textbox', { name: `Внешняя ссылка ${linkNumber}`, exact: true }).inputValue(), 'https://drive.google.com/drive/folders/reports-test');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await companyCard.evaluate(node => node.scrollWidth <= node.clientWidth + 1));
    await page.screenshot({ path: `${output}/business-company-mobile.png` });
    await companyCard.getByRole('button', { name: 'Закрыть карточку компании', exact: true }).focus();
    await page.keyboard.press('Escape');
    await companyCard.waitFor({ state: 'hidden' });
    assert.equal(await editorDraft.inputValue(), 'Черновик названия счёта');
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.reload();
    await page.locator('.edit-btn').click();
    await page.getByRole('button', { name: 'ТОО Тест · сохранено', exact: true }).first().waitFor();
    await page.locator('.editor-modal .close-btn').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('http://127.0.0.1:5192/mobile');
    // Routing may redirect /mobile to the responsive main view.
    const menu = page.locator('.user-avatar, .user-menu-btn, .mobile-user-btn').first();
    if (await menu.count()) await menu.click();
    else await page.getByRole('button', { name: /меню/i }).first().click();
    await page.getByRole('button', { name: 'Календарь задач', exact: true }).click();
    await page.getByRole('dialog', { name: 'Календарь задач', exact: true }).waitFor();
    assert.ok(await page.getByRole('dialog', { name: 'Календарь задач' }).evaluate(node => node.scrollWidth <= node.clientWidth + 1));
    await page.screenshot({ path: `${output}/business-calendar-mobile.png` });
    assert.deepEqual(errors, []);
    console.log('PASS: real Vue → HTTP → MongoDB, stacked company modal, preserved account drafts, no browser tab/navigation, explicit per-company 1C selection, no-BIN contractor import, persisted edits and Drive links, export, desktop/mobile views');
  } finally { await browser?.close(); await server.close(); }
}
